#!/usr/bin/env python3
"""Create and verify a BPS patch; never embeds or uploads a retail ROM to Git."""
import argparse
import hashlib
import struct
import zlib
from pathlib import Path

CLEAN_SHA1 = "f3ae088181bf583e55daf962a92bb46f4f1d07b7"

def number(value):
    out = bytearray()
    while True:
        byte = value & 127
        value >>= 7
        if not value:
            out.append(byte | 128)
            return out
        out.append(byte)
        value -= 1

def read_number(data, offset):
    value, shift = 0, 1
    while True:
        byte = data[offset]
        offset += 1
        value += (byte & 127) * shift
        if byte & 128:
            return value, offset
        shift <<= 7
        value += shift

def create(source, target):
    metadata = b"Pokemon Emerald: Complete Edition development alpha; new save required"
    patch = bytearray(b"BPS1") + number(len(source)) + number(len(target)) + number(len(metadata)) + metadata
    pos = 0
    while pos < len(target):
        start = pos
        if pos < len(source) and source[pos] == target[pos]:
            while pos < min(len(source), len(target)) and source[pos] == target[pos]:
                pos += 1
            patch += number(((pos - start - 1) << 2) | 0)  # SourceRead
        else:
            equal = 0
            while pos < len(target):
                equal = equal + 1 if pos < len(source) and source[pos] == target[pos] else 0
                pos += 1
                if equal == 8:
                    pos -= 8
                    break
            patch += number(((pos - start - 1) << 2) | 1)  # TargetRead
            patch += target[start:pos]
    patch += struct.pack("<II", zlib.crc32(source), zlib.crc32(target))
    patch += struct.pack("<I", zlib.crc32(patch))
    return bytes(patch)

def apply(source, patch):
    if patch[:4] != b"BPS1" or zlib.crc32(patch[:-4]) != struct.unpack("<I", patch[-4:])[0]:
        raise ValueError("Invalid BPS signature/checksum")
    source_size, offset = read_number(patch, 4)
    target_size, offset = read_number(patch, offset)
    metadata_size, offset = read_number(patch, offset)
    offset += metadata_size
    source_crc, target_crc = struct.unpack("<II", patch[-12:-4])
    if len(source) != source_size or zlib.crc32(source) != source_crc:
        raise ValueError("Wrong input ROM")
    target = bytearray()
    while len(target) < target_size:
        command, offset = read_number(patch, offset)
        length, mode = (command >> 2) + 1, command & 3
        if mode == 0:
            target += source[len(target):len(target) + length]
        elif mode == 1:
            target += patch[offset:offset + length]
            offset += length
        else:
            raise ValueError("This verifier handles SourceRead/TargetRead patches generated by this tool")
    if len(target) != target_size or offset != len(patch) - 12 or zlib.crc32(target) != target_crc:
        raise ValueError("Target checksum mismatch")
    return bytes(target)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("target", type=Path)
    parser.add_argument("patch", type=Path)
    args = parser.parse_args()
    source, target = args.source.read_bytes(), args.target.read_bytes()
    if hashlib.sha1(source).hexdigest() != CLEAN_SHA1:
        raise SystemExit("Expected clean Emerald US/EU revision 0 (SHA-1 " + CLEAN_SHA1 + ")")
    if len(target) > 32 * 1024 * 1024:
        raise SystemExit("Target exceeds standard GBA ROM capacity")
    patch = create(source, target)
    if apply(source, patch) != target:
        raise SystemExit("Patch round-trip verification failed")
    args.patch.write_bytes(patch)
    print("Verified BPS round trip; target SHA-256:", hashlib.sha256(target).hexdigest())

if __name__ == "__main__":
    main()
